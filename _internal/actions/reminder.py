def _schedule_windows(target_dt: datetime, task_name: str,
                      script_path: Path, message: str) -> str:
    python_exe = Path(sys.executable)
    pythonw = python_exe.parent / "pythonw.exe"
    if pythonw.exists():
        python_exe = pythonw

    xml_path = _scripts_dir() / f"{task_name}.xml"
    xml_content = (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        '  <RegistrationInfo><Description>J.A.R.V.I.S Reminder</Description></RegistrationInfo>\n'
        '  <Triggers><TimeTrigger>\n'
        f'    <StartBoundary>{target_dt.strftime("%Y-%m-%dT%H:%M:%S")}</StartBoundary>\n'
        '    <Enabled>true</Enabled>\n'
        '  </TimeTrigger></Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{python_exe}</Command>\n'
        f'    <Arguments>"{script_path}"</Arguments>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )

    xml_path.write_text(xml_content, encoding="utf-16")

    result = subprocess.run(
        ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path), "/F"],
        capture_output=True, text=True, encoding="utf-8", errors="replace", **_CNW,
    )

    try:
        xml_path.unlink(missing_ok=True)
    except Exception:
        pass

    if result.returncode != 0:
        script_path.unlink(missing_ok=True)
        err = (result.stderr or result.stdout).strip()
        print(f"[Reminder] ❌ schtasks: {err}")
        return ""

    return task_name


def _schedule_mac(target_dt: datetime, task_name: str,
                  script_path: Path) -> str:
    agents_dir = Path.home() / "Library" / "LaunchAgents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    label     = f"com.jarvis.reminder.{task_name}"
    plist_path = agents_dir / f"{label}.plist"

    plist_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>             <string>{label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{sys.executable}</string>
    <string>{script_path}</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Year</key>   <integer>{target_dt.year}</integer>
    <key>Month</key>  <integer>{target_dt.month}</integer>
    <key>Day</key>    <integer>{target_dt.day}</integer>
    <key>Hour</key>   <integer>{target_dt.hour}</integer>
    <key>Minute</key> <integer>{target_dt.minute}</integer>
  </dict>
  <key>RunAtLoad</key>         <false/>
  <key>StandardOutPath</key>   <string>/dev/null</string>
  <key>StandardErrorPath</key> <string>/dev/null</string>
</dict>
</plist>
"""
    plist_path.write_text(plist_content, encoding="utf-8")
    plist_path.chmod(0o644)

    result = subprocess.run(
        ["launchctl", "load", str(plist_path)],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
    )

    if result.returncode != 0:
        plist_path.unlink(missing_ok=True)
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ launchctl: {result.stderr.strip()}")
        return ""

    return label


def _schedule_linux(target_dt: datetime, task_name: str,
                    script_path: Path) -> str:

    if shutil.which("systemd-run"):
        on_calendar = target_dt.strftime("%Y-%m-%d %H:%M:00")
        result = subprocess.run(
            [
                "systemd-run",
                "--user",
                f"--on-calendar={on_calendar}",
                f"--unit={task_name}",
                "--",
                sys.executable, str(script_path),
            ],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ⚠️ systemd-run failed: {result.stderr.strip()}, trying 'at'")

    if shutil.which("at"):
        at_time = target_dt.strftime("%H:%M %Y-%m-%d")
        cmd_str = f"{sys.executable} {script_path}\n"
        result  = subprocess.run(
            ["at", at_time],
            input=cmd_str, capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ❌ at: {result.stderr.strip()}")
        return ""

    print("[Reminder] ❌ Neither systemd-run nor at found on this Linux system.")
    return ""

def cancel_os_task(task_name: str) -> bool:
    """Remove the OS-scheduler fallback for a reminder. Best effort."""
    if not task_name:
        return False
    os_name = _get_os()
    ok = False
    try:
        if os_name == "windows":
            r = subprocess.run(["schtasks", "/Delete", "/TN", task_name, "/F"],
                               capture_output=True, text=True, **_CNW)
            ok = r.returncode == 0
        elif os_name == "mac":
            plist = Path.home() / "Library" / "LaunchAgents" / f"{task_name}.plist"
            subprocess.run(["launchctl", "unload", str(plist)], capture_output=True)
            plist.unlink(missing_ok=True)
            ok = True
        else:
            r = subprocess.run(["systemctl", "--user", "stop", f"{task_name}.timer"],
                               capture_output=True, text=True)
            ok = r.returncode == 0
    except Exception:
        ok = False
    base = task_name.replace("com.jarvis.reminder.", "")
    try:
        (_scripts_dir() / f"{base}.py").unlink(missing_ok=True)
    except Exception:
        pass
    return ok


def _list_reminders() -> str:
    try:
        from core.routines import engine
        rows = engine().pending_reminders()
    except Exception as e:
        return f"Could not read reminders: {e}"
    if not rows:
        return "No reminders are pending."
    rows.sort(key=lambda r: r.get("next_run") or "")
    return "Pending reminders:\n" + "\n".join(
        f"- {r.get('next_run', '')[:16]} — {(r.get('action') or {}).get('text', '')}" for r in rows[:20])


def _cancel_reminder(text: str) -> str:
    try:
        from core.routines import engine
        eng = engine()
        rows = [r for r in eng.find(text, kind="reminder") if not r.get("fired")] if text \
            else eng.pending_reminders()[:1]
    except Exception as e:
        return f"Could not read reminders: {e}"
    if not rows:
        return "No pending reminder matches that."
    if len(rows) > 1:
        return ("status=ask action=reminder question=Which reminder: "
                + "; ".join(f"{r.get('next_run', '')[:16]} {(r.get('action') or {}).get('text', '')}"
                            for r in rows[:4])
                + "? -- NOTHING was done yet. Ask the user which one.")
    r = rows[0]
    eng.delete(r["id"])
    cancel_os_task(r.get("os_task", ""))
    return f"Cancelled the reminder for {r.get('next_run', '')[:16]}: {(r.get('action') or {}).get('text', '')}."


def reminder(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
) -> str:

    action = str(parameters.get("action") or "set").strip().lower()
    if action in ("list", "show"):
        return _list_reminders()
    if action in ("cancel", "delete", "remove"):
        return _cancel_reminder(str(parameters.get("message") or "").strip())

    date_str = parameters.get("date", "").strip()
    time_str = parameters.get("time", "").strip()
    message  = parameters.get("message", "Reminder").strip()

    if not date_str or not time_str:
        return "I need both a date and a time to set a reminder."

    try:
        target_dt = datetime.strptime(f"{date_str} {time_str}", "%Y-%m-%d %H:%M")
    except ValueError:
        return "I couldn't parse that date or time. Please use YYYY-MM-DD and HH:MM."

    if target_dt <= datetime.now():
        return "That time has already passed — I can't set a reminder in the past."

    os_name    = _get_os()
    safe_msg   = _sanitise(message)
    task_name  = f"JARVISReminder_{target_dt.strftime('%Y%m%d_%H%M%S')}"

    # Register with Mark 58's own scheduler first: while Jarvis is running he
    # speaks the reminder when it comes due. The OS job below is the fallback
    # for when he is not, and checks the scheduler's heartbeat to stay silent
    # otherwise.
    routine = None
    heartbeat = ""
    try:
        from core.routines import engine, HEARTBEAT_PATH
        routine = engine().add_reminder(target_dt, message.strip() or "Reminder",
                                        os_task=task_name)
        heartbeat = str(HEARTBEAT_PATH)
    except Exception as e:
        print(f"[Reminder] ⚠️ scheduler registration failed ({e}); OS notification only")

    try:
        script_path = _write_notify_script(task_name, safe_msg, os_name, heartbeat)
    except Exception as e:
        if routine is None:
            return f"Could not prepare the reminder script: {e}"
        script_path = None

    job_id = ""
    if script_path is not None:
        try:
            if os_name == "windows":
                job_id = _schedule_windows(target_dt, task_name, script_path, safe_msg)
            elif os_name == "mac":
                job_id = _schedule_mac(target_dt, task_name, script_path)
            else:
                job_id = _schedule_linux(target_dt, task_name, script_path)
        except Exception as e:
            script_path.unlink(missing_ok=True)
            print(f"[Reminder] ❌ Scheduling exception: {e}")

    if not job_id and routine is None:
        return "I couldn't register the reminder with the system scheduler."
    if routine is not None and job_id and job_id != task_name:
        # macOS labels differ from the task name; keep the real one for cancel.
        try:
            from core.routines import engine
            eng = engine()
            with eng._lock:
                for row in eng._routines:
                    if row["id"] == routine["id"]:
                        row["os_task"] = job_id
            eng._save()
        except Exception:
            pass

    friendly_time = target_dt.strftime("%B %d at %I:%M %p")
    if player:
        player.write_log(f"[Reminder] ✅ {date_str} {time_str} — {safe_msg[:40]}")
        try:
            player.notify("Reminder set", f"{safe_msg[:90]} · {friendly_time}", "success", 5000)
        except Exception:
            pass

    if not job_id:
        return (f"Reminder set for {friendly_time}. Jarvis will say it if he is running then; "
                "the system notification fallback could not be registered.")
    return f"Reminder set for {friendly_time}. It will be spoken when it is due."


