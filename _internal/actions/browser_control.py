# Discord web sometimes outlives the Playwright page that originally targeted
# it. Its message composer is also identified by a generated CSS class
# (``textArea_<hash>``), so treating that class as a durable browser-automation
# handle is brittle.  Once a Discord composer has been addressed successfully
# through native input, keep the next few keyboard actions on the same path so
# a normal click -> type -> Enter sequence never jumps back into a dead page.
_NATIVE_DISCORD_UNTIL = 0.0
_NATIVE_DISCORD_TTL = 15.0
_NATIVE_VISIBLE_UNTIL = 0.0
_NATIVE_VISIBLE_TTL = 15.0


def _discord_native_hint(action: str, params: dict) -> bool:
    selector = str(params.get("selector", "") or "").lower()
    desc = str(params.get("description", "") or "").lower()
    if "textarea_" in selector or "slatetextarea_" in selector:
        return action in {"click", "type"}
    if action in {"smart_click", "smart_type"} and any(
            word in desc for word in ("message", "chat", "discord")):
        try:
            from core.direct_input import focus_discord_browser
            return focus_discord_browser(params.get("browser") or "chrome").ok
        except Exception:
            return False
    return False


def _native_discord_action(action: str, params: dict, browser: str | None) -> str | None:
    """Try the real OS input path for Discord web.

    Returns None when this request is not a Discord/native-input candidate.
    Successful injection is deliberately reported as *unverified*: the OS
    accepted the focus/keystroke, but this route does not read Discord's DOM
    back afterwards and therefore must not claim delivery.
    """
    global _NATIVE_DISCORD_UNTIL

    hinted = _discord_native_hint(action, params)
    armed = time.monotonic() < _NATIVE_DISCORD_UNTIL
    if not hinted and not (armed and action in {"type", "press"}):
        return None

    try:
        from core.direct_input import (
            focus_discord_composer, press_discord, type_discord,
        )
        target_browser = browser or "chrome"
        if action in {"click", "smart_click"}:
            r = focus_discord_composer(target_browser)
            if not r.ok:
                return outcome.failed(
                    "browser_control", r.detail or "Discord composer could not be focused",
                    browser=target_browser, native_input=True)
            _NATIVE_DISCORD_UNTIL = time.monotonic() + _NATIVE_DISCORD_TTL
            return outcome.unverified(
                "browser_control",
                "Discord's visible web composer was focused through the operating system; "
                "the browser DOM was intentionally not used because its automation page may be closed",
                browser=target_browser, native_input=True, method=r.method, focused=True)

        if action in {"type", "smart_type"}:
            r = type_discord(str(params.get("text", "") or ""),
                             bool(params.get("clear_first", True)), target_browser)
            if not r.ok:
                return outcome.failed(
                    "browser_control", r.detail or "native Discord text injection failed",
                    browser=target_browser, native_input=True)
            _NATIVE_DISCORD_UNTIL = time.monotonic() + _NATIVE_DISCORD_TTL
            return outcome.unverified(
                "browser_control",
                "text was injected into Discord's visible composer through native keyboard/clipboard input; "
                "the DOM was not available to read the field back",
                browser=target_browser, native_input=True, method=r.method, typed=True)

        if action == "press":
            r = press_discord(str(params.get("key", "Enter") or "Enter"), target_browser)
            if not r.ok:
                return outcome.failed(
                    "browser_control", r.detail or "native Discord key injection failed",
                    browser=target_browser, native_input=True)
            _NATIVE_DISCORD_UNTIL = time.monotonic() + _NATIVE_DISCORD_TTL
            return outcome.unverified(
                "browser_control",
                "the key was sent to the foreground Discord browser window through native OS input; "
                "message delivery was not read back from Discord",
                browser=target_browser, native_input=True, method=r.method, key=params.get("key", "Enter"))
    except Exception as exc:
        return outcome.failed(
            "browser_control", f"native Discord input path failed: {exc}",
            browser=browser or "chrome", native_input=True)
    return None


def _native_visible_browser_action(action: str, params: dict, browser: str | None) -> str | None:
    """Directly drive a visible browser for durable chat/prompt text fields.

    This catches selectors such as ``#prompt-textarea`` before Playwright is
    involved at all. Chromium web-app inputs often remain perfectly usable on
    screen while a prior automation context is stale. Once such an input was
    focused/typed, the immediate Enter key stays on the same native path.
    """
    global _NATIVE_VISIBLE_UNTIL
    selector = str(params.get("selector", "") or "").lower()
    desc = str(params.get("description", "") or "").lower()
    durable = any(tok in selector for tok in (
        "prompt-textarea", "contenteditable", "chat-input", "message-input",
        "textarea_", "slatetextarea_"))
    smart = action in {"smart_type", "smart_click"} and any(
        tok in desc for tok in ("prompt", "message box", "chat box", "composer"))
    armed = time.monotonic() < _NATIVE_VISIBLE_UNTIL
    if not ((durable and action in {"click", "type"}) or smart
            or (armed and action == "press")):
        return None
    target = browser or _detect_default_browser() or "chrome"
    try:
        from core.direct_input import focus_browser_editable, press_browser, type_browser
        if action in {"click", "smart_click"}:
            r = focus_browser_editable(target, selector or desc)
        elif action in {"type", "smart_type"}:
            r = type_browser(str(params.get("text", "") or ""), selector or desc,
                             bool(params.get("clear_first", True)), target)
        else:
            r = press_browser(str(params.get("key", "Enter") or "Enter"), target)
        if not r.ok:
            return None  # Playwright still gets a chance.
        _NATIVE_VISIBLE_UNTIL = time.monotonic() + _NATIVE_VISIBLE_TTL
        return outcome.unverified(
            "browser_control",
            "the visible browser input was controlled through Windows accessibility/native input; "
            "this avoids brittle web-app selectors and stale browser contexts",
            browser=target, native_input=True, method=r.method, focused=True)
    except Exception:
        return None


def _native_browser_fallback(action: str, params: dict, browser: str | None) -> str | None:
    """Last-resort control of the user's visible browser after Playwright dies."""
    target = browser or _detect_default_browser() or "chrome"
    try:
        from core.direct_input import (
            focus_browser_editable, get_browser_url, hotkey_browser,
            press_browser, read_browser_text, screenshot_browser,
            scroll_browser, smart_click_browser, type_browser,
        )
        detail_value = None
        if action == "type":
            r = type_browser(str(params.get("text", "") or ""),
                             str(params.get("selector", "") or ""),
                             bool(params.get("clear_first", True)), target)
        elif action == "smart_type":
            r = type_browser(str(params.get("text", "") or ""),
                             str(params.get("description", "") or ""), True, target)
        elif action == "press":
            r = press_browser(str(params.get("key", "Enter") or "Enter"), target)
        elif action == "scroll":
            r = scroll_browser(str(params.get("direction", "down") or "down"),
                               int(params.get("amount", 500) or 500), target)
        elif action == "smart_click":
            r = smart_click_browser(str(params.get("description", "") or ""), target)
        elif action == "click":
            selector = str(params.get("selector", "") or "")
            text = str(params.get("text", "") or "")
            if text:
                r = smart_click_browser(text, target)
            elif any(token in selector.lower() for token in
                     ("textarea", "textbox", "prompt", "input", "contenteditable")):
                r = focus_browser_editable(target, selector)
            else:
                return None
        elif action == "back":
            r = hotkey_browser(("alt", "left"), target)
        elif action == "forward":
            r = hotkey_browser(("alt", "right"), target)
        elif action == "reload":
            r = hotkey_browser((("command" if _OS == "Darwin" else "ctrl"), "r"), target)
        elif action == "close_tab":
            r = hotkey_browser((("command" if _OS == "Darwin" else "ctrl"), "w"), target)
        elif action == "get_url":
            r = get_browser_url(target); detail_value = r.detail
        elif action == "get_text":
            r = read_browser_text(target); detail_value = r.detail
        elif action == "screenshot":
            r = screenshot_browser(str(params.get("path", "") or ""), target); detail_value = r.detail
        else:
            return None

        if not r.ok:
            return outcome.failed("browser_control", r.detail or "native browser fallback failed",
                                  browser=target, native_input=True, recovered_from_closed_context=True)
        if action == "get_url":
            return outcome.unverified("browser_control", "read the visible browser address bar after the automation context closed",
                                      browser=target, native_input=True, method=r.method, url=detail_value, recovered_from_closed_context=True)
        if action == "get_text":
            return outcome.unverified("browser_control", "read visible browser accessibility text after the automation context closed",
                                      browser=target, native_input=True, method=r.method, text=detail_value, recovered_from_closed_context=True)
        if action == "screenshot":
            return outcome.done("browser_control", screenshot=detail_value, native_input=True, verified=True)
        return outcome.unverified("browser_control",
            "the Playwright page/context was unavailable, so the action was sent to the user's visible browser through Windows accessibility/native input",
            browser=target, native_input=True, method=r.method, recovered_from_closed_context=True)
    except Exception as exc:
        return outcome.failed("browser_control", f"native browser fallback failed: {exc}",
                              browser=target, native_input=True, recovered_from_closed_context=True)


def browser_control(
    parameters:    dict = None,
    response=None,
    player=None,
    session_memory=None,
) -> str:
    params  = parameters or {}
    action  = params.get("action", "").lower().strip()
    browser = params.get("browser", "").lower().strip() or None
    result  = "Unknown action."

    if action == "switch":
        target = browser or params.get("target", "").lower().strip()
        result = _registry.switch(target) if target else "Please specify a browser."
        _log(player, result)
        return result

    if action == "list_browsers":
        result = _registry.list_sessions()
        _log(player, result)
        return result

    if action == "close_all":
        result = _registry.close_all()
        _log(player, result)
        return result

    if action == "close":
        target = browser or _registry._active_browser
        result = _registry.close_one(target) if target else "No browser specified."
        _log(player, result)
        return result

    # ── Navigation is ALWAYS native ──────────────────────────────────────────
    # go_to / search / new_tab open the site in the user's own browser —
    # their own profile, logged-in accounts and start page; exactly as if the
    # user had opened it themselves. A controlled window with about:blank never
    # opens here. The only exception: if an automation flow is already running,
    # navigation continues in that window (so multi-step tasks aren't split).
    if action in ("go_to", "search", "new_tab"):
        if _registry.has(browser):
            sess = _registry.get(browser)
            try:
                if action == "search":
                    result = sess.run(sess.search(params.get("query", ""),
                                                  params.get("engine", "google")))
                elif action == "new_tab":
                    result = sess.run(sess.new_tab(params.get("url", "")))
                else:
                    result = sess.run(sess.go_to(params.get("url", "")))
            except concurrent.futures.TimeoutError:
                result = f"Browser action '{action}' timed out (60s)."
            except Exception as e:
                if _closed_context_error(e):
                    # Navigation does not require DOM control. If a stale
                    # automation browser refuses recovery, hand the URL to the
                    # user's real browser immediately instead of trapping every
                    # later command behind the same dead session.
                    try:
                        _registry.close_one(sess.browser_name)
                    except Exception:
                        pass
                    if action == "search":
                        base = _SEARCH_ENGINES.get(params.get("engine", "google").lower(), _SEARCH_ENGINES["google"])
                        nav = base + params.get("query", "").replace(" ", "+")
                    else:
                        nav = params.get("url", "").strip()
                    result = _open_native(nav, browser)
                    if nav:
                        _registry.note_native_url(_normalize_url(nav))
                else:
                    result = f"Browser error ({action}): {e}"
            _log(player, result)
            return result

        if action == "search":
            base    = _SEARCH_ENGINES.get(params.get("engine", "google").lower(),
                                          _SEARCH_ENGINES["google"])
            nav_url = base + params.get("query", "").replace(" ", "+")
        else:
            nav_url = params.get("url", "").strip()

        result = _open_native(nav_url, browser)
        # Both done and unverified native outcomes mean the OS accepted the
        # navigation request; keep the URL so a later interactive action can
        # resume that page in a controllable session. Only a failed launch is
        # excluded.
        if (nav_url and (result.startswith("status=done")
                         or result.startswith("status=unverified")
                         or result.startswith("Opened"))):
            _registry.note_native_url(_normalize_url(nav_url))
        _log(player, result)
        return result

    # ── Interactive actions (click/type/read…) ───────────────────────────────
    # Discord web gets a direct OS-input route before Playwright.  This is not
    # a generic blind-click fallback: it is only selected by Discord's generated
    # composer selector (or for the immediate follow-up keypress after such a
    # selection), and it refuses to type unless a Discord browser window is
    # actually foreground.
    native_params = dict(params)
    native_params["browser"] = browser or "chrome"
    native_result = _native_discord_action(action, native_params, browser)
    if native_result is not None:
        _log(player, native_result)
        return native_result

    visible_result = _native_visible_browser_action(action, native_params, browser)
    if visible_result is not None:
        _log(player, visible_result)
        return visible_result

    # Other interactive actions use a physically controllable browser; the
    # automation window only opens here, and as soon as it opens it goes to the
    # user's last navigated page — it doesn't sit on a blank page.
    try:
        sess = _registry.get(browser)
    except Exception as e:
        result = f"Could not start browser session: {e}"
        _log(player, result)
        return result

    try:
        last = _registry.pop_native_url()
        if last:
            try:
                sess.run(sess.go_to(last))
            except Exception as e:
                print(f"[Browser] Could not resume last page ({last}): {e}")

        if action == "click":
            result = sess.run(sess.click(params.get("selector"), params.get("text")))
        elif action == "type":
            result = sess.run(sess.type_text(
                params.get("selector"), params.get("text", ""), params.get("clear_first", True)))
        elif action == "scroll":
            result = sess.run(sess.scroll(params.get("direction", "down"), int(params.get("amount", 500))))
        elif action == "fill_form":
            result = sess.run(sess.fill_form(params.get("fields", {})))
        elif action == "smart_click":
            result = sess.run(sess.smart_click(params.get("description", "")))
        elif action == "smart_type":
            result = sess.run(sess.smart_type(params.get("description", ""), params.get("text", "")))
        elif action == "get_text":
            result = sess.run(sess.get_text())
        elif action == "get_url":
            result = sess.run(sess.get_url())
        elif action == "press":
            result = sess.run(sess.press(params.get("key", "Enter")))
        elif action == "close_tab":
            result = sess.run(sess.close_tab())
        elif action == "screenshot":
            result = sess.run(sess.screenshot(params.get("path")))
        elif action == "back":
            result = sess.run(sess.back())
        elif action == "forward":
            result = sess.run(sess.forward())
        elif action == "reload":
            result = sess.run(sess.reload())
        else:
            result = f"Unknown browser action: '{action}'"

    except concurrent.futures.TimeoutError:
        result = f"Browser action '{action}' timed out (60s)."
    except Exception as e:
        if _closed_context_error(e):
            fallback = _native_browser_fallback(action, params, browser)
            result = fallback if fallback is not None else f"Browser error ({action}): {e}"
        else:
            result = f"Browser error ({action}): {e}"

    # Some action methods catch their own Playwright exception and return it as
    # text. Detect the same closed-context signature here and still recover.
    if _closed_context_error(result):
        fallback = _native_browser_fallback(action, params, browser)
        if fallback is not None:
            result = fallback

    _log(player, result)
    return result


def _log(player, text: str):
    short = str(text)[:80]
    print(f"[Browser] {short}")
    if player:
        print(f"[Browser] {short[:80]}")          # terminal, not the HUD


